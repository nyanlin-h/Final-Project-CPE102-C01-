using System.Collections.Generic;
using UnityEngine;

namespace KMUTT.ARNav
{
    public enum NavNodeType { Waypoint, Junction, Room, Stairs, Elevator, Entrance }

    /// <summary>
    /// A vertex of the navigation graph. Place on the floor surface (local y = 0 relative to its FloorRoot).
    /// Links are bidirectional; the editor tools keep both sides in sync.
    /// </summary>
    [ExecuteAlways]
    public class NavNode : MonoBehaviour
    {
        [Tooltip("Stable ID used by UI / saved destinations, e.g. 'F10_ROOM_1012'. Leave empty for plain waypoints.")]
        public string nodeId;
        public string displayName;
        public NavNodeType type = NavNodeType.Waypoint;
        public int floorLevel = 10;
        [Tooltip("Shows up in the destination picker.")]
        public bool isDestination;

        [Tooltip("Stairs/Elevator nodes on different floors with the same group are connected vertically (e.g. 'StairA', 'Lift1').")]
        public string transitionGroup;

        [Tooltip("Created by 'Generate Waypoint Grid'. Auto nodes are deleted/regenerated; hand-placed nodes never are.")]
        public bool autoGenerated;

        [Tooltip("Created by 'Import Plan Waypoints'. Re-importing replaces all of these.")]
        public bool importedFromPlan;

        [Tooltip("Links found by line-of-sight auto-linking.")]
        public List<NavNode> links = new List<NavNode>();
        [Tooltip("Hand-made links (e.g. through doors the scan didn't capture). Never cleared by tools.")]
        public List<NavNode> manualLinks = new List<NavNode>();

        public bool IsTransition => (type == NavNodeType.Stairs || type == NavNodeType.Elevator) && !string.IsNullOrEmpty(transitionGroup);

        public string Label => !string.IsNullOrEmpty(displayName) ? displayName : (!string.IsNullOrEmpty(nodeId) ? nodeId : name);

        public IEnumerable<NavNode> AllLinks()
        {
            foreach (var n in links) if (n != null) yield return n;
            foreach (var n in manualLinks) if (n != null) yield return n;
        }

#if UNITY_EDITOR
        static readonly Color[] FloorColors = { new Color(0.1f, 0.7f, 1f), new Color(1f, 0.6f, 0.1f) };

        void OnDrawGizmos()
        {
            var c = FloorColors[Mathf.Abs(floorLevel) % 2];
            if (type == NavNodeType.Stairs || type == NavNodeType.Elevator) c = Color.magenta;
            else if (isDestination) c = Color.green;
            Gizmos.color = c;
            float r = autoGenerated ? 0.08f : 0.18f;
            Gizmos.DrawSphere(transform.position + Vector3.up * 0.05f, r);

            Gizmos.color = new Color(c.r, c.g, c.b, 0.6f);
            foreach (var n in links)
                if (n != null && n.GetInstanceID() > GetInstanceID())   // draw each edge once
                    Gizmos.DrawLine(transform.position + Vector3.up * 0.05f, n.transform.position + Vector3.up * 0.05f);
            foreach (var n in manualLinks)
            {
                if (n == null || n.GetInstanceID() < GetInstanceID()) continue;
                // plan-imported corridor links use the floor colour; hand-made door links stay yellow
                Gizmos.color = (autoGenerated && n.autoGenerated) ? new Color(c.r, c.g, c.b, 0.6f) : Color.yellow;
                Gizmos.DrawLine(transform.position + Vector3.up * 0.1f, n.transform.position + Vector3.up * 0.1f);
            }
        }

        void OnDrawGizmosSelected()
        {
            if (isDestination || type != NavNodeType.Waypoint)
                UnityEditor.Handles.Label(transform.position + Vector3.up * 0.5f, Label);
        }
#endif
    }
}
